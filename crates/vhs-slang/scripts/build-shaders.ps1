# Slang → WGSL / HLSL の生成。
#
#   - generated/<module>.wgsl                           … wgpu (このクレートの参照ホスト、Tauri アプリ)
#   - generated/hlsl/<kernel>.hlsl                       … 素の HLSL (Unreal の .usf などへ組み込む元)
#   - integrations/unity/Runtime/Resources/VhsNextComposite/<kernel>.compute … Unity のコンピュートシェーダー
#
# モジュールは composite (コンポジットのエンコード → デコード) と camera (撮像管カメラ)。
#
# slangc は $env:SLANGC か PATH から探す。生成物はリポジトリに入れておき、slangc なしでもビルドできるようにする。
# HLSL は slangc の制約で 1 エントリポイント = 1 ファイルになる。

$ErrorActionPreference = 'Stop'

$crate = Split-Path -Parent $PSScriptRoot
$repo = Resolve-Path (Join-Path $crate '..\..')
$slangc = if ($env:SLANGC) { $env:SLANGC } else { (Get-Command slangc -ErrorAction Stop).Source }

$include = Join-Path $crate 'shaders'
$generated = Join-Path $crate 'generated'
$hlslDir = Join-Path $generated 'hlsl'
$unityDir = Join-Path $repo 'integrations\unity\Runtime\Resources\VhsNextComposite'
New-Item -ItemType Directory -Force $generated, $hlslDir, $unityDir | Out-Null

$modules = [ordered]@{
    'composite' = @('vhsPrepare', 'vhsEncode', 'vhsSyncAfc', 'vhsBurstLock', 'vhsSeparateDemod', 'vhsResolve')
    'camera'    = @('camOptics', 'camRowSum', 'camMean', 'camBlurH', 'camBlurV', 'camTarget', 'camProcess')
}
$kernels = @($modules.Values | ForEach-Object { $_ })

$utf8 = New-Object System.Text.UTF8Encoding($false)
function Write-Lines([string] $path, [string[]] $lines) {
    [System.IO.File]::WriteAllLines($path, $lines, $utf8)
}

function Invoke-Slangc([string[]] $arguments) {
    & $slangc @arguments
    if ($LASTEXITCODE -ne 0) { throw "slangc failed: $($arguments -join ' ')" }
}

# slangc -v prints to stderr, which Windows PowerShell 5 turns into an error record under 'Stop'
$ErrorActionPreference = 'Continue'
$version = ((& $slangc -v 2>&1) | ForEach-Object { "$_" }) -join ''
$ErrorActionPreference = 'Stop'
function Get-Banner([string] $module) {
    "// Generated by scripts/build-shaders.ps1 from crates/vhs-slang/shaders/$module.slang (slangc $version). Do not edit."
}

# 消えたカーネルの生成物を残さない (Unity の .meta も一緒に消す)
Get-ChildItem $hlslDir -Filter *.hlsl | Where-Object { $kernels -notcontains $_.BaseName } | Remove-Item
Get-ChildItem $unityDir -Filter *.compute | Where-Object { $kernels -notcontains $_.BaseName } |
    ForEach-Object { Remove-Item $_.FullName; Remove-Item "$($_.FullName).meta" -ErrorAction SilentlyContinue }

foreach ($module in $modules.Keys) {
    $source = Join-Path $crate "shaders\$module.slang"
    $banner = Get-Banner $module

    # WGSL: すべてのエントリポイントを 1 ファイルに出せる
    $wgsl = Join-Path $generated "$module.wgsl"
    Invoke-Slangc @($source, '-I', $include, '-target', 'wgsl', '-line-directive-mode', 'none', '-o', $wgsl)
    Write-Lines $wgsl ((@($banner) + (Get-Content $wgsl)))

    foreach ($kernel in $modules[$module]) {
        $hlsl = Join-Path $hlslDir "$kernel.hlsl"
        # -no-mangle: リソース名を Slang の宣言のまま残す (Unity / Unreal は名前でバインドする)
        Invoke-Slangc @($source, '-I', $include, '-target', 'hlsl', '-entry', $kernel, '-stage', 'compute',
            '-no-mangle', '-line-directive-mode', 'none', '-o', $hlsl)
        $body = Get-Content $hlsl
        Write-Lines $hlsl ((@($banner) + $body))

        $compute = Join-Path $unityDir "$kernel.compute"
        $header = @($banner, "#pragma kernel $kernel", '')
        Write-Lines $compute (($header + $body))
    }
}

Write-Host "Generated WGSL, $($kernels.Count) HLSL kernels and Unity compute shaders with slangc $version"
