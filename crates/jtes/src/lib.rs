//! 日本のアナログテレビ文字多重放送 (JTES、ITU-R BT.653 Teletext System D) の送出と受信。
//!
//! 映像信号のサンプル列 (`&mut [f32]`、1 ラインぶん) に波形を足す・そこからパケットを取り出すところから、
//! データグループ・番組データ・8 単位符号・受信機の画面の組み立てまでを受け持つ。ライン番号の割り当てや
//! 信号レベルの単位、画面への描画は呼び出し側が決める。
//!
//! 規格 (郵政省告示第125号 別表第一号、BT.653-3 Table 1b System D):
//!
//! ```text
//! 番組データ               = 番組管理データ + ページデータ (データヘッダ + データユニット …)
//! データグループ           = SOH + ヘッダ + … + ETB/ETX/EOT + CRC-16 (単位ごと)
//! データライン (296 ビット) = クロックラン 16 + フレーミングコード 8 + データパケット 272
//! データパケット (272)     = プレフィックス 14 + データブロック 176 (22 バイト) + チェック 82
//! プレフィックス           = サービス識別 4 + チェック 4 ((8,4) 拡大ハミング) + CI 4 + フラグ 2
//! チェック符号             = (272,190) 短縮化差集合巡回符号 (Weldon の (273,191) を 1 ビット短縮)
//! 物理層                   = 2 値 NRZ、364 fH (5.727272 Mbit/s)、"1" = 70 %、ロールオフ 0.6、同期前縁から 56 Tc
//! ```
//!
//! - [`packet`] — プレフィックス・データブロック・データラインのビット配置
//! - [`fec`] — (272,190) 符号器と多数決論理復号器
//! - [`wave`] — ロールオフ 0.6 の余弦ロールオフ整形での描画と、受信側のスライス
//! - [`group`] — データグループ (SOH/STX/ETB/ETX/EOT、CRC-16) の組み立てと受信側の再構成
//! - [`program`] — 番組データヘッダ・ページデータヘッダ・送出スケジュールと、受信機 ([`program::Receiver`])
//! - [`code`] — 8 単位符号 (本文・ヘッダ文) の符号化と、受信側の画面 ([`code::Screen`])
//! - [`font`] — JIS C 6226-1983 の 16 ドット字形 (jiskan16)

pub mod code;
